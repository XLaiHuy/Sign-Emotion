import { readFile, writeFile, mkdir, copyFile, readdir, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
const hash = (data) => createHash('sha256').update(data).digest('hex');
const lock = JSON.parse(await readFile('scripts/conversation-assets.lock.json', 'utf8'));
// Product profile: Vietnamese-finetuned PhoWhisper tiny first, with Whisper
// tiny retained as a load fallback; VAD captions and PhoBERT text analysis.
// Experimental speech-emotion and Whisper-base models are intentionally not shipped.
const packs = { speech: [], emotion: [] };
for (const asset of lock.assets) {
  const target = resolve('public' + asset.url);
  await mkdir(dirname(target), { recursive: true });
  let data;
  try {
    data = await readFile(target);
  } catch {
    /* first preparation */
  }
  if (!data || data.length !== asset.bytes || hash(data) !== asset.sha256) {
    console.log(`Preparing ${asset.url}`);
    const response = await fetch(asset.source, { signal: AbortSignal.timeout(300_000) });
    if (!response.ok) throw new Error(`Asset HTTP ${response.status}: ${asset.url}`);
    data = Buffer.from(await response.arrayBuffer());
    if (data.length !== asset.bytes || hash(data) !== asset.sha256)
      throw new Error(`Checksum mismatch: ${asset.url}`);
    await writeFile(target, data);
  }
  packs[asset.pack].push(asset);
}
// Transformers.js 3 has a different ORT build from the face runtime. Keep its
// matching WASM/loader together; never substitute binaries between versions.
const runtime = resolve('node_modules/@huggingface/transformers/node_modules/onnxruntime-web');
const info = JSON.parse(await readFile(resolve(runtime, 'package.json'), 'utf8'));
await mkdir('public/runtime/speech', { recursive: true });
let runtimeAssetCount = 0;
// Remove only the obsolete pair generated by the previous loader, not caches
// or user files. Transformers.js uses the matching JSEP pair below.
for (const file of ['ort-wasm-simd-threaded.mjs', 'ort-wasm-simd-threaded.wasm'])
  await rm(`public/runtime/speech/${file}`, { force: true });
for (const file of await readdir(resolve(runtime, 'dist'))) {
  if (!/^ort-wasm-simd-threaded\.jsep\.(mjs|wasm)$/.test(file)) continue;
  await copyFile(resolve(runtime, 'dist', file), `public/runtime/speech/${file}`);
  const data = await readFile(`public/runtime/speech/${file}`);
  const asset = {
    url: `/runtime/speech/${file}`,
    bytes: data.length,
    sha256: hash(data),
    source: `onnxruntime-web@${info.version}/dist/${file}`,
    license: 'MIT',
  };
  packs.speech.push(asset);
  runtimeAssetCount++;
}
if (runtimeAssetCount !== 2)
  throw new Error(`Expected both speech runtime files, found ${runtimeAssetCount}`);
for (const id of Object.keys(packs))
  if (!packs[id].length) throw new Error(`Required conversation pack is empty: ${id}`);
const manifest = {
  version: 'conversation-v2',
  packs: Object.entries(packs)
    .filter(([, assets]) => assets.length)
    .map(([id, assets]) => ({ id, assets, experimental: id === 'emotion' })),
};
await writeFile(
  'public/models/conversation-manifest.json',
  JSON.stringify(manifest, null, 2) + '\n',
);
console.log(
  `Prepared product profile: ${manifest.packs.map((p) => `${p.id} ${(p.assets.reduce((sum, a) => sum + a.bytes, 0) / 1048576).toFixed(1)} MiB`).join(', ')}`,
);
